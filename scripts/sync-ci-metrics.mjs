// sync-ci-metrics.mjs - pull the Fusion NIDS test numbers from live CI and write them
// into the site, so nobody types them by hand again.
//
// Why this exists: the project card claimed "144 tests passing, 79% coverage". Live CI
// said 292 passed. Between the issue being filed and being fixed the real number moved
// from 266 to 292, which is the whole argument - a number typed into HTML is wrong the
// moment the suite changes, and nothing tells you.
//
// Two suites report different things and neither is lying:
//   - CI (.github/workflows/ci.yml) runs `pytest -q` with NO coverage flag.
//     Gives a test count, no coverage. Runs on every push.
//   - Extended Validation runs the coverage gate. Gives coverage. Runs rarely;
//     last green 2026-07-02.
// So the test count is refreshed here and coverage is quoted with its date, because a
// bare "79%" implies a freshness the project does not have.
//
// Usage:  node scripts/sync-ci-metrics.mjs [--check]
//   (no flag)  fetch, write public/ci-metrics.json, rewrite the marked span in index.html
//   --check    fail with exit 1 if the committed numbers are stale. For CI.
//
// Needs the gh CLI authenticated. Read-only against GitHub.

import { execFileSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 's-shahzad/fusion-nids';
const OUT_JSON = path.join(ROOT, 'public', 'ci-metrics.json');
const INDEX = path.join(ROOT, 'index.html');

const START = '<!-- ci-metrics:start -->';
const END = '<!-- ci-metrics:end -->';

// Coverage is not produced by the main CI workflow. Carried here with the run that
// produced it so the date always travels with the number.
const COVERAGE = { percent: 75.83, floor: 72, run_id: 28607694888, measured_at: '2026-07-02', workflow: 'Extended Validation' };

const GH = process.platform === 'win32' ? 'C:\\Program Files\\GitHub CLI\\gh.exe' : 'gh';

function gh(args) {
  return execFileSync(GH, args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

function latestGreenCiRun() {
  const raw = gh(['run', 'list', '--repo', REPO, '--workflow', 'CI', '--branch', 'main',
    '--status', 'success', '--limit', '1', '--json', 'databaseId,createdAt,headSha']);
  const runs = JSON.parse(raw);
  if (!runs.length) throw new Error(`no successful CI run found on ${REPO}@main`);
  return runs[0];
}

// pytest's own summary line is the only thing trusted here. Parsing prose would just
// move the drift problem somewhere less visible.
function parseCounts(log) {
  const re = /(\d+) passed(?:, (\d+) skipped)?(?:, (\d+) deselected)?/g;
  let best = null, m;
  while ((m = re.exec(log)) !== null) {
    const passed = Number(m[1]);
    if (!best || passed > best.passed) {
      best = { passed, skipped: Number(m[2] || 0), deselected: Number(m[3] || 0) };
    }
  }
  if (!best) throw new Error('no pytest summary line in CI log');
  return best;
}

function build() {
  const run = latestGreenCiRun();
  const log = gh(['run', 'view', String(run.databaseId), '--repo', REPO, '--log']);
  const counts = parseCounts(log);
  return {
    source: `https://github.com/${REPO}/actions/runs/${run.databaseId}`,
    run_id: run.databaseId,
    commit: run.headSha,
    ran_at: run.createdAt,
    synced_at: new Date().toISOString(),
    tests: counts,
    coverage: COVERAGE,
    note: 'Generated by scripts/sync-ci-metrics.mjs. Do not hand-edit; run the script.',
  };
}

// The sentence the site shows. One place, so the JSON and the HTML cannot disagree.
function sentence(m) {
  return `${m.tests.passed} tests passing (CI, ${m.ran_at.slice(0, 10)}) &middot; ` +
         `${m.coverage.percent}% coverage at ${m.coverage.measured_at}`;
}

function rewriteIndex(m) {
  const html = fs.readFileSync(INDEX, 'utf8');
  const s = html.indexOf(START), e = html.indexOf(END);
  if (s === -1 || e === -1) {
    throw new Error(`markers ${START} / ${END} not found in index.html - add them around the metrics text`);
  }
  const next = html.slice(0, s + START.length) + sentence(m) + html.slice(e);
  if (next === html) return false;
  fs.writeFileSync(INDEX, next);
  return true;
}

const check = process.argv.includes('--check');
const metrics = build();

if (check) {
  const onDisk = fs.existsSync(OUT_JSON) ? JSON.parse(fs.readFileSync(OUT_JSON, 'utf8')) : null;
  const stale = !onDisk || onDisk.tests.passed !== metrics.tests.passed;
  if (stale) {
    console.error(`STALE: site says ${onDisk ? onDisk.tests.passed : 'nothing'}, CI says ${metrics.tests.passed}.`);
    console.error('Run: node scripts/sync-ci-metrics.mjs');
    process.exit(1);
  }
  console.log(`ok - ${metrics.tests.passed} tests, matches CI run ${metrics.run_id}`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT_JSON), { recursive: true });
fs.writeFileSync(OUT_JSON, JSON.stringify(metrics, null, 2) + '\n');
const changed = rewriteIndex(metrics);
console.log(`wrote ${path.relative(ROOT, OUT_JSON)}`);
console.log(`index.html ${changed ? 'updated' : 'already current'}`);
console.log(`  ${sentence(metrics).replace('&middot;', '/')}`);
